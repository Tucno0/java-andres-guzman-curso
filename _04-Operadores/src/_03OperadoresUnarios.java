public class _03OperadoresUnarios {
    public static void main(String[] args) {
    
        // Operadores unarios
        int i = -5;
        int j = +i; // j = (1) * i => -5
        System.out.println("i = " + i);
        
        int k = -i; // k = (-1) * i => 5
        System.out.println("k = " + k);
        
        i = 6;
        j = +i; // j = (1) * i => 6
        System.out.println("j = " + j);
        
        k = -i; // k = (-1) * i => -6
        System.out.println("k = " + k);
    }
}
